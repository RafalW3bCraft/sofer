import { useState } from "react";
import { explainWithAi, type AiExplainState } from "../lib/ai";
import type { ExplainContext } from "../../../shared/schemas";

interface Props {
  context: ExplainContext;
  arabic: string;
  lessonId?: string;
  tokenIndex?: number;
}

function uuidv4(): string {
  // Browser-safe UUID v4 using crypto.randomUUID when available.
  const c = (globalThis as { crypto?: Crypto }).crypto;
  if (c && typeof c.randomUUID === "function") {
    return c.randomUUID();
  }
  const bytes = new Uint8Array(16);
  if (c && typeof c.getRandomValues === "function") {
    c.getRandomValues(bytes);
  } else {
    for (let i = 0; i < 16; i++) bytes[i] = Math.floor(Math.random() * 256);
  }
  bytes[6] = ((bytes[6] ?? 0) & 0x0f) | 0x40;
  bytes[8] = ((bytes[8] ?? 0) & 0x3f) | 0x80;
  const hex = Array.from(bytes, (b) => b.toString(16).padStart(2, "0")).join("");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

export default function AiTutorButton({
  context,
  arabic,
  lessonId,
  tokenIndex,
}: Props) {
  const [state, setState] = useState<AiExplainState>({ kind: "idle" });

  const handleClick = async () => {
    setState({ kind: "loading" });
    const result = await explainWithAi({
      context,
      arabic,
      lessonId: lessonId ?? "unknown",
      tokenIndex,
      requestId: uuidv4(),
    });
    setState(result);
  };

  if (state.kind === "idle" || state.kind === "loading") {
    return (
      <button
        type="button"
        className="btn"
        onClick={handleClick}
        disabled={state.kind === "loading"}
        aria-busy={state.kind === "loading"}
      >
        {state.kind === "loading" ? "Asking the tutor…" : "Explain with AI tutor"}
      </button>
    );
  }

  if (state.kind === "ok") {
    return (
      <section className="token-panel" aria-label="AI tutor explanation">
        <p style={{ fontSize: "0.85rem", color: "var(--color-text-soft)" }}>
          Generated by AI · Model {state.response.model} ·{" "}
          {new Date(state.response.generatedAt).toLocaleTimeString()}
        </p>
        <p style={{ whiteSpace: "pre-wrap" }}>{state.response.explanation}</p>
        <button type="button" className="btn btn--ghost" onClick={() => setState({ kind: "idle" })}>
          Close
        </button>
      </section>
    );
  }

  // fallback
  return (
    <section className="token-panel" aria-label="AI tutor unavailable">
      <p style={{ fontSize: "0.85rem", color: "var(--color-text-soft)" }}>
        AI tutor unavailable — using the curated explanation.
      </p>
      <p style={{ whiteSpace: "pre-wrap" }}>{state.message}</p>
      <button type="button" className="btn btn--ghost" onClick={() => setState({ kind: "idle" })}>
        Close
      </button>
    </section>
  );
}